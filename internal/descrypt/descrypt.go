// bit は 1 始まりの番号で 64 ビット値のビットを取り出す (MSB が 1 番)。
func bit(v uint64, n byte) uint64 { return (v >> (64 - uint(n))) & 1 }

// permute は table に従ってビットを並べ替える。in は幅 inBits (MSB 詰め)。
func permute(in uint64, inBits uint, table []byte) uint64 {
	var out uint64
	for _, t := range table {
		out = out<<1 | (in>>(inBits-uint(t)))&1
	}
	return out
}

// keySchedule は 64 ビット鍵から 16 ラウンド分の 48 ビット部分鍵を作る。
func keySchedule(key uint64) [16]uint64 {
	cd := permute(key, 64, pc1[:])
	c := uint32(cd >> 28)
	d := uint32(cd & 0x0fffffff)
	var ks [16]uint64
	for i := 0; i < 16; i++ {
		for s := byte(0); s < shifts[i]; s++ {
			c = ((c << 1) | (c >> 27)) & 0x0fffffff
			d = ((d << 1) | (d >> 27)) & 0x0fffffff
		}
		ks[i] = permute(uint64(c)<<28|uint64(d), 56, pc2[:])
	}
	return ks
}

// feistel は 1 ラウンドの f 関数。salt で入れ替えた E テーブルを使うのが crypt(3) の特徴。
func feistel(r uint32, k uint64, e *[48]byte) uint32 {
	x := permute(uint64(r), 32, e[:]) ^ k
	var out uint32
	for i := 0; i < 8; i++ {
		six := byte(x >> (uint(7-i) * 6) & 0x3f)
		row := (six&0x20)>>4 | six&1
		col := (six >> 1) & 0x0f
		out = out<<4 | uint32(sBox[i][row*16+col])
	}
	return uint32(permute(uint64(out), 32, pTable[:]))
}

func encrypt(block uint64, ks *[16]uint64, e *[48]byte) uint64 {
	v := permute(block, 64, ip[:])
	l := uint32(v >> 32)
	r := uint32(v)
	for i := 0; i < 16; i++ {
		l, r = r, l^feistel(r, ks[i], e)
	}
	return permute(uint64(r)<<32|uint64(l), 64, fp[:])
}

// Crypt は crypt(3) と同じ 13 文字のハッシュを返す。
// password は先頭 8 文字だけが使われる (crypt(3) の仕様)。
func Crypt(password, salt string) (string, error) {
	if len(salt) < 2 {
		return "", fmt.Errorf("salt は 2 文字必要です")
	}
	sv := [2]int{}
	for i := 0; i < 2; i++ {
		v := indexOf(salt[i])
		if v < 0 {
			return "", fmt.Errorf("salt に使えない文字です: %q", salt[i])
		}
		sv[i] = v
	}

	// パスワードの各バイトを 1 ビット左に詰めて 56 ビット鍵にする。
	var key uint64
	for i := 0; i < 8; i++ {
		var c byte
		if i < len(password) {
			c = password[i]
		}
		key = key<<8 | uint64(c<<1)
	}
	ks := keySchedule(key)

	// salt の 12 ビットで E テーブルの i 番目と i+24 番目を入れ替える。
	e := eTable
	saltBits := sv[0] | sv[1]<<6
	for i := 0; i < 12; i++ {
		if saltBits>>uint(i)&1 == 1 {
			e[i], e[i+24] = e[i+24], e[i]
		}
	}

	var block uint64
	for i := 0; i < 25; i++ {
		block = encrypt(block, &ks, &e)
	}

	out := make([]byte, 0, 13)
	out = append(out, salt[0], salt[1])
	// 64 ビットを先頭から 6 ビットずつ 11 文字に。最後の 1 文字は残り 4 ビット + ゼロ 2 ビット。
	for i := 0; i < 11; i++ {
		out = append(out, alphabet[block>>58&0x3f])
		block <<= 6
	}
	return string(out), nil
}

// NewSalt は暗号学的に安全な乱数で 2 文字の salt を作る。
func NewSalt() (string, error) {
	var b [2]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", err
	}
	return string([]byte{alphabet[b[0]&0x3f], alphabet[b[1]&0x3f]}), nil
}

func indexOf(c byte) int {
	for i := 0; i < len(alphabet); i++ {
		if alphabet[i] == c {
			return i
		}
	}
	return -1
}
